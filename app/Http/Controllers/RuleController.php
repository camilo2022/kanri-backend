     *                 type="object",
     *                 @OA\Property(
     *                     property="id",
     *                     type="array",
     *
     *                     @OA\Items(type="string", example="No hay ningún registro.")
     *                 )
     *             )
     *         )
     *     ),
     *
     *     @OA\Response(
     *         response=401,
     *         description="No autenticado",
     *
     *         @OA\JsonContent(
     *             ref="#/components/schemas/UnauthorizedResponse"
     *         )
     *     ),
     *
     *     @OA\Response(
     *         response=500,
     *         description="Error del servidor",
     *
     *         @OA\JsonContent(
     *             ref="#/components/schemas/ServerErrorResponse"
     *         )
     *     )
     * )
     */
    public function restore(RuleRestoreRequest $request, $id)
    {
        try {
            $rule = Rule::withTrashed()->findOrFail($id);
            $rule->restore();

            return $this->successResponse(
                new RuleResource($rule),
                $this->getMessage('Success'),
                200
            );
        } catch (\Throwable $e) {
            return $this->errorResponse(
                [
                    'message' => $this->getMessage(class_basename($e)),
                    'error' => $e->getMessage(),
                ],
                $this->getCode(class_basename($e))
            );
        }
    }

    public function setting(RuleSettingRequest $request, $id)
    {
        try {

            $item = DB::table('items')->where('id', $id)->first();

            $settings = json_decode($item->settings ?? '{}', true) ?: [];
            $settings['weights'] = $request->input('settings.weights');

            DB::table('items')
                ->where('id', $id)
                ->update([
                    'settings' => json_encode($settings),
                    'updated_at' => now(),
                ]);

            return $this->successResponse(
                ['id' => $id, 'settings' => $settings],
                $this->getMessage('Success'),
                200
            );
        } catch (\Throwable $e) {
            return $this->errorResponse(
                ['message' => $this->getMessage(class_basename($e)), 'error' => $e->getMessage()],
                $this->getCode(class_basename($e))
            );
        }
    }
