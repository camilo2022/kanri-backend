                ->filter(fn ($config) => isset($config['model']))
                ->each(function ($config, $key) use ($rule, $relations) {
                    $value = $relations[$key] ?? null;
                    $rule->related($config['model'])->sync(filled($value) ? Arr::wrap($value) : []);
