    public function all(RuleAllRequest $request)
    {
        try {
            $rules = Rule::query()
                ->when($request->filled('search'), function ($query) use ($request) {
                    return $query->search($request->input('search'));
                })
                ->when($request->boolean('with_trashed'), function ($query) {
                    return $query->withTrashed();
                })
                ->when(
                    $request->filled('column') && $request->filled('dir'),
                    function ($query) use ($request) {
                        return $query->orderBy(
                            $request->input('column'),
                            $request->input('dir')
                        );
                    }
                );

            $rules = $rules->paginate(
                $request->integer('per_page', $rules->count())
            );

            $item = DB::table('items')
                ->where('id', Rule::ITEM_ID)
                ->first();

            if ($item && isset($item->settings)) {
                $item->settings = json_decode($item->settings);
            }

            return $this->successResponse(
                new RuleCollection($rules, $item),
                $this->getMessage('Success'),
                200
            );
        } catch (\Throwable $e) {
            return $this->errorResponse(
                [
                    'message' => $this->getMessage(class_basename($e)),
                    'error' => $e->getMessage(),
                ],
                $this->getCode(class_basename($e))
            );
        }
    }

